function abrirModulo(id) {
    const area = document.getElementById('areaModulo');
    const titulo = document.getElementById('tituloModulo');
    const lista = document.getElementById('listaTitulos');
    const explicacao = document.getElementById('explicacaoConteudo');

    titulo.innerText = modulos[id].titulo;
    explicacao.innerText = ""; // limpa explicação anterior

    // limpar lista antes
    lista.innerHTML = "";

    modulos[id].topicos.forEach((topico, index) => {
        const li = document.createElement('li');
        li.innerText = topico.titulo;
        li.onclick = () => { explicacao.innerText = topico.explicacao; };
        lista.appendChild(li);
    });

    area.style.display = 'block';
}

function fecharModulo() {
    document.getElementById('areaModulo').style.display = 'none';
}